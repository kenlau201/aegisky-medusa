// Merge all terms
const ALL_TERMS: Record<string, string> = {
  ...TECH_TERMS,
  ...EXTENDED_TERMS,
}

// Build lookup maps for fast translation
const TERM_SORTED = Object.entries(ALL_TERMS).sort((a, b) => b[0].length - a[0].length)
const TERM_MAP = new Map<string, string>()
TERM_SORTED.forEach(([ru, en]) => {
  TERM_MAP.set(ru.toLowerCase(), en)
})

// Build exact match lookup
const EXACT_LOOKUP = new Map<string, string>()
;[...Object.entries(CATEGORY_TRANSLATIONS), ...Object.entries(ATTRIBUTE_TRANSLATIONS), 
 ...Object.entries(ATTRIBUTE_VALUE_TRANSLATIONS), ...Object.entries(EXTENDED_TERMS),
 ...Object.entries(TECH_TERMS)].forEach(([k, v]) => {
  EXACT_LOOKUP.set(k.toLowerCase(), v)
})

/**
 * Translate text content using word-by-word replacement (optimized)
 */
export function translateText(text: string): string {
  if (!text) return text

  // Try exact match first (case-insensitive)
  const exact = EXACT_LOOKUP.get(text.toLowerCase())
  if (exact) return exact

  // Split text into words and translate each word
  // This is faster than complex regex for large dictionaries
  return text.replace(/[а-яА-ЯёЁ]+(?:\s+[а-яА-ЯёЁ]+)*/g, (match) => {
    const lower = match.toLowerCase()
    // Try multi-word match first
    const translated = TERM_MAP.get(lower)
    if (translated) {
      // Preserve capitalization of first letter
      if (match[0] === match[0].toUpperCase()) {
        return translated.charAt(0).toUpperCase() + translated.slice(1)
      }
      return translated
    }
    // Try single word match (split by spaces)
    const words = match.split(/\s+/)
    const translatedWords = words.map(word => {
      const w = word.toLowerCase()
      const t = TERM_MAP.get(w)
      if (t) {
        if (word[0] === word[0].toUpperCase()) {
          return t.charAt(0).toUpperCase() + t.slice(1)
        }
        return t
      }
      return word
    })
    return translatedWords.join(' ')
  })
}

/**
 * Translate HTML content while preserving tags
 */
export function translateHtmlContent(html: string): string {
  if (!html) return html

  let result = html

  // Remove script and style tags content (keep tags but empty them)
  result = result.replace(/<script[^>]*>[\s\S]*?<\/script>/gi, '<script></script>')
  result = result.replace(/<style[^>]*>[\s\S]*?<\/style>/gi, '<style></style>')

  // Fix video tags: convert <video><a href="url.mp4">url</a></video> to proper HTML5 video
  result = result.replace(/<video([^>]*)>([\s\S]*?)<\/video>/gi, (match, attrs, inner) => {
    // Extract video URL from href
    const hrefMatch = inner.match(/href=["']([^"']+\.(?:mp4|webm|mov))["']/i)
    if (hrefMatch) {
      const videoUrl = hrefMatch[1]
      // Ensure controls attribute
      const videoAttrs = attrs.includes('controls') ? attrs : attrs + ' controls'
      const widthMatch = videoAttrs.match(/width=["']?(\d+)/i)
      const width = widthMatch ? widthMatch[1] : '640'
      return `<div class="video-wrapper" style="position:relative;max-width:100%;margin:1rem 0;"><video${videoAttrs} style="max-width:100%;height:auto;border-radius:8px;background:#000;" preload="metadata" playsinline><source src="${videoUrl}" type="video/mp4" />Your browser does not support the video tag. <a href="${videoUrl}" target="_blank" rel="noopener">Download video</a></video></div>`
    }
    return match
  })

  // Check if content has significant Cyrillic
  const cyrillicCount = (result.match(/[\u0400-\u04FF]/g) || []).length
  if (cyrillicCount < 5) return result // Skip if mostly already English

  // Translate text between tags
  // Match text nodes (content between > and < that contains non-whitespace)
  result = result.replace(/>([^<]+)</g, (match, textContent) => {
    const trimmed = textContent.trim()
    if (!trimmed) return match
    // Skip if it's just numbers, punctuation, or already English
    if (/^[\d\s.,;:!?()\-–—_+=*/\\|@#$%^&<>[\]{}"'`~]+$/.test(trimmed)) return match
    if (!/[\u0400-\u04FF]/.test(trimmed)) return match
    // Skip URLs
    if (/^https?:\/\//i.test(trimmed)) return match
    const translated = translateText(trimmed)
    return '>' + textContent.replace(trimmed, translated) + '<'
  })

  // Translate alt and title attributes
  result = result.replace(/\b(alt|title|placeholder)="([^"]*[\u0400-\u04FF][^"]*)"/gi, (match, attr, value) => {
    return `${attr}="${translateText(value)}"`
  })

  return result
}
