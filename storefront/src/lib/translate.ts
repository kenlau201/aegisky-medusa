/**
 * Translate a Russian product name to professional English
 */
export function translateProductName(name: string): string {
  if (!name) return name
  let result = name

  // Replace technical terms (longer phrases first to avoid partial matches)
  const sortedTerms = Object.entries(ALL_TERMS).sort((a, b) => b[0].length - a[0].length)
  for (const [ru, en] of sortedTerms) {
    const escaped = ru.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    const regex = new RegExp(`(?<![a-zA-Zа-яА-Я])${escaped}(?![a-zA-Zа-яА-Я])`, 'gi')
    result = result.replace(regex, en)
  }

  // Clean up extra spaces
  result = result.replace(/\s+/g, ' ').trim()

  // Capitalize properly
  result = result.split(' ').map(word => {
    if (!word) return word
    const lower = word.toLowerCase()
    if (['for', 'with', 'and', 'in', 'on', 'to', 'of', 'the', 'a', 'an'].includes(lower)) {
      return lower
    }
    // Keep technical abbreviations uppercase
    if (/^(ESC|VTX|VRX|FC|BEC|DShot|SBUS|PPM|GPS|FPV|RTF|LiPo|LiHV|XT60|XT90|JST|CCW|CW|KV|TVL|RTK|DJI|HD|4K|8K|UHD|FHD|HDMI|USB|SD|LED|OSD|UART|I2C|SPI|PWM|CAN)$/i.test(word)) {
      return word.toUpperCase()
    }
    return word.charAt(0).toUpperCase() + word.slice(1).toLowerCase()
  }).join(' ')

  return result
}

export function translateCategoryName(name: string): string {
  return CATEGORY_TRANSLATIONS[name] || translateProductName(name)
}

export function translateAttributeName(name: string): string {
  return ATTRIBUTE_TRANSLATIONS[name] || translateProductName(name)
}

export function translateAttributeValue(value: string): string {
  return ATTRIBUTE_VALUE_TRANSLATIONS[value] || translateProductName(value)
}

