const allCats = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', 'wc-categories-full.json'), 'utf-8'));

// 建立映射
const categoryMap = new Map(); // wcCategoryId → mainCategoryId
const unmapped = [];

for (const cat of allCats) {
  const decodedSlug = decodeSlug(cat.slug).toLowerCase();
  const nameLower = cat.name.toLowerCase();
  
  let mapped = false;
  
  // 1. 先精确匹配名称
  for (const main of MAIN_CATEGORIES) {
    if (nameLower === main.name.toLowerCase()) {
      categoryMap.set(cat.id, main.id);
      mapped = true;
      break;
    }
  }
  
  // 2. 再匹配slug关键词
  if (!mapped) {
    for (const main of MAIN_CATEGORIES) {
      if (decodedSlug.includes(main.slug)) {
        categoryMap.set(cat.id, main.id);
        mapped = true;
        break;
      }
    }
  }
  
  // 3. 品牌映射
  if (!mapped) {
    for (const [brandSlug, mainId] of Object.entries(BRAND_MAP)) {
      if (decodedSlug.includes(brandSlug) || nameLower.includes(brandSlug)) {
        categoryMap.set(cat.id, mainId);
        mapped = true;
        break;
      }
    }
  }
  
  if (!mapped) {
    unmapped.push(cat);
  }
}

