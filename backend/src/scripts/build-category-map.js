const productMainCats = new Map(); // productId → Set of mainCategoryIds

for (const file of files) {
  const products = JSON.parse(fs.readFileSync(path.join(DATA_DIR, file), 'utf-8'));
  for (const p of products) {
    const mainCats = new Set();
    if (p.categories) {
      for (const cat of p.categories) {
        const mainId = categoryMap.get(cat.id);
        if (mainId) mainCats.add(mainId);
      }
    }
    productMainCats.set(p.id, mainCats);
    for (const mc of mainCats) {
      mainCounts[mc]++;
    }
  }
}

